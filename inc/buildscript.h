#ifndef BUILDSCRIPT_H
#define BUILDSCRIPT_H

/* Build scripts: Make.sh (Linux/macOS, bash) and Make.bat (Windows), in the
 * style the Vircon32 ecosystem uses -- one step per tool, `|| abort_build`
 * after each, BUILD SUCCESSFUL/FAILED at the end -- generated from the same
 * information emit_cart_xml has (the source, the -o path, the #texture /
 * #sound hints, -b), so they never drift from the XML they pack.
 *
 * What a script does, in order: check the tools are in PATH (v32c++ and the
 * Vircon32 DevTools are required; v32opt is optional), create obj/ and bin/,
 * run v32c++ again on the source (with the same -I/-D/-U/-b/-g options and
 * --no-build-scripts, so the script is never rewritten while it runs),
 * compile, assemble, convert every texture and sound, and pack the ROM. If
 * v32opt is found when the script RUNS, the optimized path (v32opt ->
 * <name>Opt.asm -> <name>Opt.vbin -> <name>Opt.xml -> bin/<name>Opt.v32) is
 * built too; otherwise it is skipped with a note.
 *
 * Location (also the preserve-paths XML's, see cartxml.h): beside the source file, or -- when the source sits in a `src`
 * directory whose parent has (or receives, per -o) an `obj` directory --
 * in that parent. Every path inside is relative to the script's directory.
 *
 * An existing Make.sh/Make.bat that v32c++ did not write (its first lines
 * lack the "Generated by v32c++" marker) is never overwritten; a warning
 * says so.
 *
 * `prog` is the name v32c++ was invoked as ("v32c++" or "v32c"); the scripts
 * check for and call that. `args`/`arg_is_path`: the v32c++ command-line options to repeat when the
 * script runs v32c++ (never the input, -o, -x, -v or --no-build-scripts).
 * An argument flagged as a path (the directory after -I) is rewritten
 * relative to the script's directory. */
void emit_build_scripts(const char *prog, const char *output_filename, const char *source_filename,
                        int is_bios, int preserve_paths,
                        const char *const *args, const int *arg_is_path,
                        int arg_count);

/* Where the scripts go (malloc'd directory; caller frees). */
char *build_script_dir(const char *output_filename, const char *source_filename);

#endif /* BUILDSCRIPT_H */
