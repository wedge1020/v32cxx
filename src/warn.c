#include <stdarg.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "warn.h"

typedef struct { const char *name; const char *what; } WarnKind;

static const WarnKind g_kinds[] = {
    { "rom",                 "an __attribute__((rom)) array that cannot be placed in ROM" },
    { "unsigned",            "`unsigned` is treated as plain int" },
    { "dropped-args",        "arguments given to a function declared without parameters are dropped" },
    { "lib-duplicate",       "a symbol defined in two members of a library" },
    { "build-script",        "a Make.sh / Make.bat that cannot be written or was not generated by v32c++" },
    { "cart-name",           "two cart assets that get the same name in the XML" },
    { "vector-destructor",   "std::vector of a class with a destructor" },
    { "ptr-return-write",    "a write through a pointer returned by a call" },
    { "compound-side-effect","a compound assignment whose target has a side effect" },
    { "macro-redefined",     "a macro redefined with a different body" },
    { "include-guard",       "an include guard that is already defined" },
    { "include-in-body",     "an #include inside a { } body that is not expanded" },
    { "sdk-header-missing",  "an SDK header that cannot be found (its types are unknown)" },
    { "pragma",              "a #pragma that is ignored" },
    { "static-assert",       "a static_assert condition that cannot be evaluated" },
    { "bit-field",           "a bit-field stored as a full word" },
    { "undefined-reference", "a function or extern variable used and never defined (--allow-undefined)" },
    { "no-effect",           "a statement with no effect" },
    { "dynamic-cast",        "dynamic_cast, which is not checked at run time" },
};
#define NKINDS ((int)(sizeof g_kinds / sizeof g_kinds[0]))

static int g_all_errors = 0;
static unsigned char g_kind_error[NKINDS];
static int g_total = 0, g_errors = 0;

static int kind_index(const char *name) {
    for (int i = 0; i < NKINDS; i++)
        if (strcmp(g_kinds[i].name, name) == 0) return i;
    return -1;
}

int warn_error_enable(const char *list) {
    if (list == NULL || *list == '\0') { g_all_errors = 1; return 0; }
    char *copy = strdup(list);
    int rc = 0;
    char *tok = copy;
    while (tok != NULL) {
        char *comma = strchr(tok, ',');
        if (comma != NULL) *comma = '\0';
        const char *name = tok;
        if (strncmp(name, "-W", 2) == 0) name += 2;
        if (*name != '\0') {
            int k = kind_index(name);
            if (k < 0) {
                fprintf(stderr, "error: --warn-error: '%s' is not a warning kind (see --list-warnings)\n", name);
                rc = -1;
            } else {
                g_kind_error[k] = 1;
            }
        }
        tok = comma != NULL ? comma + 1 : NULL;
    }
    free(copy);
    return rc;
}

void v32_warnf(const char *kind, const char *fmt, ...) {
    char buf[4096];
    va_list ap;
    va_start(ap, fmt);
    vsnprintf(buf, sizeof buf, fmt, ap);
    va_end(ap);
    size_t n = strlen(buf);
    int had_newline = n > 0 && buf[n - 1] == '\n';
    if (had_newline) buf[--n] = '\0';
    fprintf(stderr, "%s [-W%s]\n", buf, kind);
    g_total++;
    int k = kind_index(kind);
    if (g_all_errors || (k >= 0 && g_kind_error[k])) g_errors++;
}

int warn_count(void) { return g_total; }
int warn_error_count(void) { return g_errors; }

void warn_list_kinds(void) {
    for (int i = 0; i < NKINDS; i++) printf("%-20s %s\n", g_kinds[i].name, g_kinds[i].what);
}
